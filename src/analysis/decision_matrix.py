"""
Deployment decision matrix synthesized strictly from one benchmark session's measurements.

Only configurations that pass BOTH the numerical-parity gate and the task-quality gate are eligible for a
recommendation; every statement in the generated table is derived from the aggregated session data.
"""

from pathlib import Path
from typing import List, Optional
import pandas as pd

from src.common.logging import setup_logger

logger = setup_logger("decision_matrix")


def _label(r: pd.Series) -> str:
    return f"{r['runtime']} ({r['provider']}) {str(r['precision']).upper()}"


def synthesize_decision_matrix(df: pd.DataFrame, output_path: Optional[Path] = None, e2e_budget_ms: float = 10.0) -> str:
    lines: List[str] = [
        "# Deployment Decision Matrix",
        "",
        "Generated by `src/analysis/decision_matrix.py` from a single benchmark session"
        + (f" (`{df['session_id'].iloc[0]}`)" if not df.empty and "session_id" in df else "")
        + ". Only configurations that pass both the numerical-parity gate and the task-quality gate are eligible. "
        "Measurements are from the disclosed workstation testbed (batch size 1), not from embedded hardware.",
        "",
        "| Scenario | Selection rule | Recommendation | Evidence |",
        "| :--- | :--- | :--- | :--- |",
    ]
    if df.empty:
        lines.append("| - | - | No benchmark data | Run `scripts/benchmark_all.py` |")
        content = "\n".join(lines) + "\n"
        if output_path:
            Path(output_path).write_text(content, encoding="utf-8")
        return content

    ok = df[df["numerical_gate"].astype(bool) & df["quality_passed"].astype(bool)]

    det = ok[ok["model"] == "yolo_nano"]
    if not det.empty:
        r = det.sort_values("p50_e2e_ms").iloc[0]
        meets = "meets" if r["p50_e2e_ms"] <= e2e_budget_ms else "does NOT meet"
        lines.append(
            f"| A. Lowest end-to-end latency, detector | min E2E p50 | {_label(r)} | "
            f"E2E p50 {r['p50_e2e_ms']:.2f} ms ({meets} a {e2e_budget_ms:.0f} ms budget), model p50 {r['p50_model_ms']:.3f} ms, "
            f"mAP@50 {r['quality_value']:.4f} ({r['quality_delta']:+.4f}) |"
        )

    for model, title in (("yolo_nano", "detector"), ("industrial_autoencoder", "autoencoder")):
        cpu = ok[(ok["model"] == model) & ok["provider"].str.contains("CPU")]
        if not cpu.empty:
            r = cpu.sort_values("p50_model_ms").iloc[0]
            lines.append(
                f"| B. CPU-only host, {title} | min model p50 on CPU | {_label(r)} | "
                f"model p50 {r['p50_model_ms']:.3f} ms (95% CI {r['p50_model_ci_low_ms']:.3f}-{r['p50_model_ci_high_ms']:.3f}), "
                f"{r['speedup_model']:.2f}x vs PyTorch FP32 CPU, {r['quality_metric']} {r['quality_value']:.4f} |"
            )

    ae = ok[ok["model"] == "industrial_autoencoder"]
    if not ae.empty:
        r = ae.sort_values(["quality_value", "p50_e2e_ms"], ascending=[False, True]).iloc[0]
        lines.append(
            f"| C. Anomaly inspection, best image AUROC | max AUROC, then min E2E p50 | {_label(r)} | "
            f"image AUROC {r['quality_value']:.4f} ({r['quality_delta']:+.4f} vs FP32 reference), E2E p50 {r['p50_e2e_ms']:.2f} ms |"
        )

    files = ok[ok["model_size_source"] == "serialized_file"]
    for model, g in files.groupby("model", sort=False):
        r = g.sort_values(["model_size_mb", "p50_model_ms"]).iloc[0]
        lines.append(
            f"| D. Smallest deployable artifact, {model} | min serialized size | {_label(r)} | "
            f"{r['model_size_mb']:.2f} MB ({r['storage_compression_pct']:.1f}% smaller than FP32 ONNX), "
            f"{r['quality_metric']} delta {r['quality_delta']:+.4f}, {r['speedup_vs_runtime_fp32']:.2f}x vs same-runtime FP32 |"
        )

    rejected = df[~(df["numerical_gate"].astype(bool) & df["quality_passed"].astype(bool))]
    lines += ["", "## Configurations excluded by acceptance gates", ""]
    if rejected.empty:
        lines.append("None: every measured configuration passed the numerical-parity and task-quality gates.")
    else:
        for _, r in rejected.iterrows():
            lines.append(
                f"- `{r['model']}` {_label(r)}: numerical gate {'PASS' if r['numerical_gate'] else 'FAIL'} "
                f"(max rel. error {r['max_rel_error']:.2e}, cosine {r['cosine_similarity']:.6f}), quality gate "
                f"{'PASS' if r['quality_passed'] else 'FAIL'} ({r['quality_metric']} delta {r['quality_delta']:+.4f})."
            )
    unstable = df[~df["stable"].astype(bool)]
    if not unstable.empty:
        lines += ["", f"Note: {len(unstable)} of {len(df)} configurations exceeded the session-median CV threshold "
                  f"(see `cv_p50` in `results/runs.csv`); their latencies vary between sessions on this host."]

    content = "\n".join(lines) + "\n"
    if output_path:
        p = Path(output_path)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content, encoding="utf-8")
        logger.info(f"Decision matrix -> {p}")
    return content
